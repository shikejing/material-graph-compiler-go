package compiler

import (
	"crypto/sha256"
	"encoding/hex"
	"sort"
	"strings"
	"sync"
)

// Session is the high-level compiler entry point. It owns the node library,
// the result and fragment caches, and coordinates concurrent compilation with
// singleflight semantics.
type Session struct {
	lib      *NodeLibrary
	results  *ResultCache
	frags    *FragmentCache
	mu       sync.Mutex
	inflight map[string]*call
}

type call struct {
	done chan struct{}
	res  *CompileResult
}

// NewSession creates a session with the given library and cache capacities.
func NewSession(lib *NodeLibrary, resultCap, fragCap int) *Session {
	return &Session{
		lib:      lib,
		results:  NewResultCache(resultCap),
		frags:    NewFragmentCache(fragCap),
		inflight: map[string]*call{},
	}
}

// Library returns the session's node library.
func (s *Session) Library() *NodeLibrary { return s.lib }

// graphKey computes the result-cache key for a graph: it depends only on the
// graph content and the node library version.
func graphKey(g *Graph, libVersion int) string {
	sum := sha256.Sum256([]byte(g.Canonical() + "|lib" + itoa(libVersion)))
	return hex.EncodeToString(sum[:])
}

// Compile compiles a single graph, using caches and singleflight. Concurrent
// requests for the same graph share a single compilation.
func (s *Session) Compile(g *Graph) *CompileResult {
	key := graphKey(g, s.lib.Version())

	// Fast path: result cache hit.
	if r, ok := s.results.Get(key); ok {
		return r
	}

	s.mu.Lock()
	if r, ok := s.results.Get(key); ok {
		s.mu.Unlock()
		return r
	}
	if c, ok := s.inflight[key]; ok {
		s.mu.Unlock()
		<-c.done
		return c.res
	}
	c := &call{done: make(chan struct{})}
	s.inflight[key] = c
	s.mu.Unlock()

	res := s.compile(g, key)

	s.mu.Lock()
	c.res = res
	close(c.done)
	delete(s.inflight, key)
	s.mu.Unlock()

	s.results.Put(key, res)
	return res
}

// compile performs the actual compilation: migrate, validate, optimize,
// fragment-level compile with caching, and program assembly.
func (s *Session) compile(g *Graph, key string) *CompileResult {
	// 1. Migrate to current library versions.
	migrated, migDiags := MigrateGraph(s.lib, g)
	if HasError(migDiags) {
		return &CompileResult{GraphKey: key, Diagnostics: migDiags, Success: false}
	}

	// 2. Validate.
	valDiags := ValidateGraph(s.lib, migrated)
	if HasError(valDiags) {
		return &CompileResult{GraphKey: key, Diagnostics: append(migDiags, valDiags...), Success: false}
	}

	// 3. Optimize (constant folding + dead-code elimination).
	opt := Optimize(s.lib, migrated)
	diags := append(migDiags, valDiags...)
	diags = append(diags, opt.Diags...)

	// 4. Fragment-level compilation in deterministic topological order.
	order := topologicalOrder(migrated)
	upstreamKeys := map[string]string{}
	upstreamFrags := map[string]*Fragment{}
	var reused, recompiled, eliminated, folded []string

	for _, id := range order {
		if !opt.LiveNodes[id] {
			eliminated = append(eliminated, id)
			continue
		}
		n := migrated.Nodes[id]
		fkey := FragmentKey(s.lib, migrated, n, opt, upstreamKeys)
		upstreamKeys[id] = fkey
		if f, ok := s.frags.Get(fkey); ok {
			upstreamFrags[id] = f
			reused = append(reused, id)
			continue
		}
		f, fdiags := compileNode(s.lib, migrated, n, opt, upstreamFrags)
		if HasError(fdiags) {
			return &CompileResult{GraphKey: key, Diagnostics: append(diags, fdiags...), Success: false}
		}
		s.frags.Put(fkey, f)
		upstreamFrags[id] = f
		recompiled = append(recompiled, id)
		if opt.Folded[id] != nil {
			folded = append(folded, id)
		}
	}
	// Nodes not in the topological order but present in the graph are dead.
	for _, id := range migrated.NodeIDs() {
		if !opt.LiveNodes[id] {
			eliminated = append(eliminated, id)
		}
	}

	// 5. Assemble the program deterministically.
	var code strings.Builder
	code.WriteString("// Auto-generated by material-graph-compiler. Do not edit.\n")
	code.WriteString("// graph: ")
	code.WriteString(key)
	code.WriteString(" lib:")
	code.WriteString(itoa(s.lib.Version()))
	code.WriteString("\n// Deterministic: no timestamps or random identifiers.\n\n")
	code.WriteString("vec4 material() {\n")
	for _, id := range order {
		if !opt.LiveNodes[id] {
			continue
		}
		f := upstreamFrags[id]
		if f == nil || f.Folded {
			continue
		}
		code.WriteString(f.Code)
	}
	outFrag := upstreamFrags[migrated.OutputNode]
	outVar := "0.0"
	if outFrag != nil {
		if v, ok := outFrag.Vars["result"]; ok {
			outVar = v
		}
	}
	code.WriteString("    return ")
	code.WriteString(outVar)
	code.WriteString(";\n}\n")

	// 6. Build the report with sorted lists for determinism.
	sort.Strings(reused)
	sort.Strings(recompiled)
	sort.Strings(eliminated)
	sort.Strings(folded)
	report := &CompileReport{
		Reused:     reused,
		Recompiled: recompiled,
		Eliminated: eliminated,
		Folded:     folded,
	}
	prog := &Program{GraphKey: key, LibVersion: s.lib.Version(), Code: code.String()}
	return &CompileResult{
		GraphKey:    key,
		Program:     prog,
		Diagnostics: diags,
		Report:      report,
		Success:     true,
	}
}

// BatchCompile compiles multiple graphs independently, isolating failures. Each
// graph's result is returned in the same order as the input.
func (s *Session) BatchCompile(graphs []*Graph) []*CompileResult {
	results := make([]*CompileResult, len(graphs))
	for i, g := range graphs {
		results[i] = s.Compile(g)
	}
	return results
}
